#!/usr/bin/env python3
"""Round R, section 12 -- the internal symmetry of an A trail-version used to reduce the kappa = 4, 5 searches.
For a shift s, the map run k -> k + s (mod m) is an automorphism of the single-visit problem of one trail-version when
  (a) the run-level weight matrix is invariant: W[k + s, l + s] = W[k, l] for all k, l (the chains, the kappa of
      every Hamiltonian path and the search tree from y0 + s are then the images of those from y0), and
  (b) the effective slack table of dominance_slack.c is invariant: S[y + s, x + s] = S[y, x].
Then a visit (y, x, kappa) is undominated iff (y + s, x + s, kappa) is, so it suffices to search the start runs
y0 in [0, s).  The shift is induced by a relabeling of the 8 symbols (printed).
usage: version_shift_symmetry.py RUNS.bin TRAIL VERSION SLACK.bin OUT.json"""
import sys, json, struct, hashlib
import numpy as np

def load_runs(path):
    raw = open(path, 'rb').read(); off = 0; runs = {}
    for t in range(30):
        for v in range(2):
            mm = struct.unpack_from('<i', raw, off)[0]; off += 4
            runs[(t, v)] = np.frombuffer(raw[off:off + 8 * mm], dtype=np.uint8).reshape(mm, 8).copy(); off += 8 * mm
    return runs

def weights(R):
    m = len(R); first = R.astype(int); last = np.concatenate([R[:, 7:8], R[:, :7]], axis=1).astype(int)
    W = np.full((m, m), 8)
    for s in range(7, 0, -1):
        eq = np.ones((m, m), bool)
        for i in range(8 - s): eq &= (last[:, s + i][:, None] == first[:, i][None, :])
        W = np.where(eq, s, W)
    np.fill_diagonal(W, 99)
    return W

def main():
    runs = load_runs(sys.argv[1]); T0, V0 = int(sys.argv[2]), int(sys.argv[3]); R = runs[(T0, V0)]; m = len(R)
    W = weights(R)
    Sraw = open(sys.argv[4], 'rb').read(); S = np.frombuffer(Sraw, dtype=np.int8).reshape(m, m).astype(int)
    out = dict(trail=T0, version=V0, runs=m, slack_sha256=hashlib.sha256(Sraw).hexdigest(), shifts=[])
    for s in range(1, m):
        idx = (np.arange(m) + s) % m
        wi = bool(np.array_equal(W[np.ix_(idx, idx)], W)); si = bool(np.array_equal(S[np.ix_(idx, idx)], S))
        if not wi: continue
        pi = {}; ok = True
        for k in range(m):
            for a, b in zip(R[k], R[(k + s) % m]):
                if pi.setdefault(int(a), int(b)) != int(b): ok = False
        out['shifts'].append(dict(shift=s, W_invariant=wi, S_invariant=si, symbol_relabeling=pi if ok else None))
    good = [d['shift'] for d in out['shifts'] if d['W_invariant'] and d['S_invariant']]
    out['least_automorphism_shift'] = min(good) if good else None
    out['automorphism_shifts'] = good
    out['conclusion'] = ('the shifts form the cyclic group generated by %d; start runs y0 in [0, %d) represent all %d start runs' % (min(good), min(good), m)) if good and all(g % min(good) == 0 for g in good) and len(good) == m // min(good) - 1 else 'see shifts'
    print(json.dumps(out)); json.dump(out, open(sys.argv[5], 'w'), indent=1)

main()
